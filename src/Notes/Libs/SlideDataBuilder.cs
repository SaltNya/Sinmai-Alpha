                    case 5:
                        tmp = (i - 1) & 7;
                        tmp2 = (i - 2) & 7;
                        HitAreasLookup[key] =
                        [
                            new HitAreaData(0.25, 0.34, [i]),
                            new HitAreaData(0.54, 0.68, [i | 8, tmp | 8]),
                            new HitAreaData(0.85, 0.90, [tmp2 | 8, 16]),
                            new HitAreaData(1.00, 1.00, [j | 8])
