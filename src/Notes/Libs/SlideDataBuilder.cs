                            new HitAreaData(1.00, 1.00, [i])
                        ];
                        break;
                    default:
                        break;
                }
                // C <-> Bj
                key = (16 << 5) | (j | 8);
                key2 = ((j | 8) << 5) | 16;
                HitAreasLookup[key] =
                [
                    new HitAreaData(0.50, 0.70, [16]),
